#!/usr/bin/env bash
set -euo pipefail
umask 077

CLIENTS="both"
REFRESH_KEYS=false
ALL_DEVICES=true
SELECTED_DEVICES=()
CONFIG_DIR="${XDG_CONFIG_HOME:-${HOME}/.config}/ci-agent-sync"
CREDENTIALS_FILE="${CONFIG_DIR}/nanokvm.env"
LOCAL_BIN="${HOME}/.local/bin"

SERVERS=(
  nanokvm-beta-ms-a2-kvm
  nanokvm-core-14-kvm
  nanokvm-core-17-kvm
  nanokvm-core-4-kvm
  nanokvm-core-5-kvm
  nanokvm-core-7-kvm
)
HOSTS=(
  beta-ms-a2-kvm
  core-14-kvm
  core-17-kvm
  core-4-kvm
  core-5-kvm
  core-7-kvm
)
KEY_VARS=(
  NANOKVM_BETA_MS_A2_KVM_API_KEY
  NANOKVM_CORE_14_KVM_API_KEY
  NANOKVM_CORE_17_KVM_API_KEY
  NANOKVM_CORE_4_KVM_API_KEY
  NANOKVM_CORE_5_KVM_API_KEY
  NANOKVM_CORE_7_KVM_API_KEY
)

usage() {
  cat <<'EOF'
Set up the six CI NanoKVM MCP servers for Claude Code, Codex CLI, or both.

Usage:
  ./scripts/setup-nanokvm-mcp.sh [--clients both|claude|codex] [--device HOST] [--refresh-keys]

Options:
  --clients VALUE  Configure both clients (default), Claude Code, or Codex CLI.
  --device HOST    Configure one KVM; repeat to select several. Default: all six.
  --refresh-keys   Prompt for new keys for the selected KVMs.
  -h, --help       Show this help.

API keys are read with terminal echo disabled and saved outside the repository.
EOF
}

fail() {
  printf 'Error: %s\n' "$1" >&2
  exit 1
}

while (($#)); do
  case "$1" in
    --clients)
      (($# >= 2)) || fail "--clients needs a value"
      CLIENTS="$2"
      shift 2
      ;;
    --device)
      (($# >= 2)) || fail "--device needs a value"
      ALL_DEVICES=false
      SELECTED_DEVICES+=("$2")
      shift 2
      ;;
    --refresh-keys)
      REFRESH_KEYS=true
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      fail "unknown option: $1"
      ;;
  esac
done

case "$CLIENTS" in
  both|claude|codex) ;;
  *) fail "--clients must be both, claude, or codex" ;;
esac

is_selected_device() {
  local host="$1"
  local selected
  [[ "$ALL_DEVICES" == true ]] && return 0
  for selected in "${SELECTED_DEVICES[@]}"; do
    [[ "$selected" == "$host" ]] && return 0
  done
  return 1
}

if [[ "$ALL_DEVICES" != true ]]; then
  ((${#SELECTED_DEVICES[@]} > 0)) || fail "select at least one --device"
  for selected in "${SELECTED_DEVICES[@]}"; do
    found=false
    for host in "${HOSTS[@]}"; do
      if [[ "$selected" == "$host" ]]; then
        found=true
        break
      fi
    done
    [[ "$found" == true ]] || fail "unknown device: $selected"
  done
fi

CLAUDE_BIN=""
CODEX_BIN=""
if [[ "$CLIENTS" == both || "$CLIENTS" == claude ]]; then
  CLAUDE_BIN="$(type -P claude || true)"
  [[ -n "$CLAUDE_BIN" ]] || fail "Claude Code CLI was not found on PATH"
fi
if [[ "$CLIENTS" == both || "$CLIENTS" == codex ]]; then
  CODEX_BIN="$(type -P codex || true)"
  [[ -n "$CODEX_BIN" ]] || fail "Codex CLI was not found on PATH"
fi

mkdir -p "$CONFIG_DIR"
chmod 700 "$CONFIG_DIR"

# Keep caller-supplied values across loading the prior private key file.
OVERRIDES=()
for env_var in "${KEY_VARS[@]}"; do
  OVERRIDES+=("${!env_var:-}")
done

if [[ -f "$CREDENTIALS_FILE" ]]; then
  # This is the local file generated by this script, containing shell-quoted assignments.
  # shellcheck disable=SC1090
  source "$CREDENTIALS_FILE"
fi

KEYS=()
for i in "${!KEY_VARS[@]}"; do
  env_var="${KEY_VARS[$i]}"
  if [[ -n "${OVERRIDES[$i]}" ]]; then
    printf -v "$env_var" '%s' "${OVERRIDES[$i]}"
  fi
  key="${!env_var:-}"
  if is_selected_device "${HOSTS[$i]}" && [[ "$REFRESH_KEYS" == true ]]; then
    key=""
  fi
  if is_selected_device "${HOSTS[$i]}" && [[ -z "$key" ]]; then
    [[ -t 0 ]] || fail "No saved key for ${SERVERS[$i]}; run this script in a terminal to enter it"
    read -r -s -p "API key for ${SERVERS[$i]}: " key || fail "Could not read API key"
    printf '\n'
  fi
  if is_selected_device "${HOSTS[$i]}"; then
    [[ -n "$key" ]] || fail "API key for ${SERVERS[$i]} cannot be empty"
    printf -v "$env_var" '%s' "$key"
    export "$env_var"
  fi
  KEYS+=("$key")
done

CREDENTIALS_TMP="$(mktemp "${CONFIG_DIR}/nanokvm.env.XXXXXX")"
trap 'rm -f "$CREDENTIALS_TMP"' EXIT
{
  for i in "${!KEY_VARS[@]}"; do
    if [[ -n "${KEYS[$i]}" ]]; then
      printf 'export %s=' "${KEY_VARS[$i]}"
      printf '%q\n' "${KEYS[$i]}"
    fi
  done
} >"$CREDENTIALS_TMP"
chmod 600 "$CREDENTIALS_TMP"
mv "$CREDENTIALS_TMP" "$CREDENTIALS_FILE"
trap - EXIT

mkdir -p "$LOCAL_BIN"

write_wrapper() {
  local client="$1"
  local binary="$2"
  local wrapper="${LOCAL_BIN}/nanokvm-${client}"
  local tmp
  tmp="$(mktemp "${LOCAL_BIN}/.nanokvm-${client}.XXXXXX")"
  {
    printf '#!/usr/bin/env bash\nset -euo pipefail\n'
    printf 'source %q\n' "$CREDENTIALS_FILE"
    printf 'exec %q "$@"\n' "$binary"
  } >"$tmp"
  chmod 700 "$tmp"
  mv "$tmp" "$wrapper"
}

if [[ "$CLIENTS" == both || "$CLIENTS" == codex ]]; then
  for i in "${!SERVERS[@]}"; do
    is_selected_device "${HOSTS[$i]}" || continue
    name="${SERVERS[$i]}"
    url="https://${HOSTS[$i]}.capybara-ulmer.ts.net/api/mcp"
    codex mcp remove "$name" >/dev/null 2>&1 || true
    codex mcp add "$name" --url "$url" --bearer-token-env-var "${KEY_VARS[$i]}"
  done
  write_wrapper codex "$CODEX_BIN"
fi

if [[ "$CLIENTS" == both || "$CLIENTS" == claude ]]; then
  for i in "${!SERVERS[@]}"; do
    is_selected_device "${HOSTS[$i]}" || continue
    name="${SERVERS[$i]}"
    url="https://${HOSTS[$i]}.capybara-ulmer.ts.net/api/mcp"
    env_var="${KEY_VARS[$i]}"
    header="Authorization: Bearer \${${env_var}}"
    claude mcp remove --scope user "$name" >/dev/null 2>&1 || true
    claude mcp add --transport http --scope user "$name" "$url" --header "$header"
  done
  write_wrapper claude "$CLAUDE_BIN"
fi

printf '\nNanoKVM MCP setup complete for %s.\n' "$CLIENTS"
if [[ "$ALL_DEVICES" == true ]]; then
  printf 'Configured devices: all six\n'
else
  printf 'Configured devices: %s\n' "${SELECTED_DEVICES[*]}"
fi
printf 'Private API keys: %s (mode 600)\n' "$CREDENTIALS_FILE"
if [[ "$CLIENTS" == both || "$CLIENTS" == claude ]]; then
  printf 'Start Claude Code with: %s/nanokvm-claude\n' "$LOCAL_BIN"
fi
if [[ "$CLIENTS" == both || "$CLIENTS" == codex ]]; then
  printf 'Start Codex CLI with:   %s/nanokvm-codex\n' "$LOCAL_BIN"
fi
printf 'The client configs contain environment-variable references, not API key values.\n'
